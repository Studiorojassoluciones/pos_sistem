CREATE TABLE IF NOT EXISTS products (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  stock NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cash_sessions (
  cash_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opening_cash NUMERIC(12,2) NOT NULL CHECK (opening_cash >= 0),
  closing_cash NUMERIC(12,2) CHECK (closing_cash IS NULL OR closing_cash >= 0),
  status VARCHAR(10) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_cash_sessions_open
  ON cash_sessions (status)
  WHERE status = 'open';

CREATE TABLE IF NOT EXISTS customers (
  customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(254),
  phone VARCHAR(30),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sales (
  sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cash_session_id BIGINT NOT NULL REFERENCES cash_sessions(cash_session_id),
  customer_id INTEGER REFERENCES customers(customer_id),
  subtotal NUMERIC(12,2) NOT NULL,
  tax NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL,
  payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('cash', 'card', 'transfer')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_sales_amounts CHECK (subtotal >= 0 AND tax >= 0 AND total = subtotal + tax)
);

CREATE TABLE IF NOT EXISTS sale_items (
  sale_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES sales(sale_id),
  product_id INTEGER NOT NULL REFERENCES products(product_id),
  quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE IF NOT EXISTS inventory_movements (
  movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(product_id),
  quantity_change NUMERIC(12,3) NOT NULL,
  reason VARCHAR(30) NOT NULL CHECK (reason IN ('adjustment', 'sale')),
  sale_id BIGINT REFERENCES sales(sale_id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_sales_created_at ON sales (created_at DESC);
CREATE INDEX IF NOT EXISTS ix_sales_customer_created_at ON sales (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_sale_items_sale_id ON sale_items (sale_id);
